import {readFileSync, writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const maximumArity = 32;
const output = fileURLToPath(new URL('../src/gargamelle/record.gleam', import.meta.url));
const check = process.argv.slice(2);
if (check.length > 1 || check.some(arg => arg !== '--check')) {
  throw new Error('Usage: node verification/generate-record.mjs [--check]');
}

let source = `//// Pipe-friendly static record definitions with ordinary constructors.
//// Each field consumes one constructor argument and retains the existing core
//// types and semantics. Field operations run only while the Result is Ok;
//// the first DefinitionError is returned unchanged. Argument expressions are
//// evaluated eagerly, including after an earlier error. Construction and finish
//// do not invoke the record constructor or decoding converters.

// Generated by verification/generate-record.mjs. Regenerate with
// npm run generate:record; verify with npm run check:record.

import gargamelle
import gleam/option.{type Option}
import gleam/result

/// Start with an explicitly curried constructor, without invoking it.
/// The recursion environment remains inferred from subsequent fields and use.
pub fn start(constructor: a) -> Result(gargamelle.Record(a, r), gargamelle.DefinitionError) {
  Ok(gargamelle.record(constructor))
}
`;

for (let arity = 1; arity <= maximumArity; arity++) {
  const args = Array.from({length: arity}, (_, i) => `a${i + 1}`);
  const values = args.map((_, i) => `value${i + 1}`);
  const curriedType = args.reduceRight((tail, arg) => `fn(${arg}) -> ${tail}`, 'output');
  const call = `constructor(${values.join(', ')})`;
  const curry = values.reduceRight((tail, value) => `fn(${value}) { ${tail} }`, call);
  source += `
/// Start with an ordinary ${arity}-argument constructor, without invoking it.
pub fn start${arity}(constructor: fn(${args.join(', ')}) -> output)
  -> Result(gargamelle.Record(${curriedType}, r), gargamelle.DefinitionError) {
  start(${arity === 1 ? 'constructor' : curry})
}
`;
}

source += `
/// Add a required field only when the preceding construction succeeded.
/// Consume one constructor argument; preserve the first error unchanged.
pub fn required(
  record: Result(gargamelle.Record(fn(a) -> b, r), gargamelle.DefinitionError),
  name: String,
  child: gargamelle.Plan(a, r),
) -> Result(gargamelle.Record(b, r), gargamelle.DefinitionError) {
  use fields <- result.try(record)
  gargamelle.required(fields, name, child)
}

/// Add an optional field only when the preceding construction succeeded.
/// Consume an Option(a) argument; absence is None and present values use the child.
pub fn optional(
  record: Result(gargamelle.Record(fn(Option(a)) -> b, r), gargamelle.DefinitionError),
  name: String,
  child: gargamelle.Plan(a, r),
) -> Result(gargamelle.Record(b, r), gargamelle.DefinitionError) {
  use fields <- result.try(record)
  gargamelle.optional(fields, name, child)
}

/// Add a defaulted field only when the preceding construction succeeded.
/// The core builder validates the admitted default without decoding it.
/// An absent field decodes its default; present invalid input still fails.
pub fn defaulted(
  record: Result(gargamelle.Record(fn(a) -> b, r), gargamelle.DefinitionError),
  name: String,
  child: gargamelle.Plan(a, r),
  value: gargamelle.Json,
) -> Result(gargamelle.Record(b, r), gargamelle.DefinitionError) {
  use fields <- result.try(record)
  gargamelle.defaulted(fields, name, child, value)
}

/// Finish a successful record with the existing extra-field policy.
/// The remaining constructor type becomes the decoded output type, as in core.
/// An explicit Definition(Output) return annotation checks field completeness.
/// A preceding construction error is returned unchanged.
pub fn finish(
  record: Result(gargamelle.Record(a, r), gargamelle.DefinitionError),
  policy: gargamelle.RecordPolicy,
) -> Result(gargamelle.Plan(a, r), gargamelle.DefinitionError) {
  result.map(record, fn(fields) { gargamelle.finish(fields, policy) })
}
`;

const formatted = spawnSync('gleam', ['format', '--stdin'], {input: source, encoding: 'utf8'});
if (formatted.error) throw formatted.error;
if (formatted.status !== 0) throw new Error(formatted.stderr);
if (check.length) {
  if (readFileSync(output, 'utf8') !== formatted.stdout) {
    throw new Error('Generated record module is stale; run npm run generate:record');
  }
  console.log(`Generated record module is current (arities 1–${maximumArity}).`);
} else {
  writeFileSync(output, formatted.stdout);
  console.log(`Generated ${output} (arities 1–${maximumArity}).`);
}
